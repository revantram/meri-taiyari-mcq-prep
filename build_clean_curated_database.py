    if any(k in combo for k in ["उपग्रह", "satellite", "nvs"]): return "satellite"
    if any(k in combo for k in ["अभ्यास", "नौसैनिक अभ्यास", "सैन्य अभ्यास"]): return "defense"
    if any(k in combo for k in ["बुलेट ट्रेन", "कॉरिडोर"]): return "corridor"
    if any(k in combo for k in ["अभिनेता", "अभिनेत्री"]): return "actor"
    if any(k in combo for k in ["फिल्म", "मूवी"]): return "film"
    if any(k in combo for k in ["राज्य में", "किस राज्य"]): return "state"
    return "city"

