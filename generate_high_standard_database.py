def pick_distractors(ans, cat):
    pool = DISTRACTORS.get(cat, DISTRACTORS["district"])
    ans_clean = str(ans).strip()
    cands = [d for d in pool if d.strip() != ans_clean]
    rng = random.Random(abs(hash(ans_clean)) % 1000)
    rng.shuffle(cands)
    return cands[:3]

